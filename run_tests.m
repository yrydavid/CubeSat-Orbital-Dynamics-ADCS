%% CubeSat: unit tests and short end-to-end smoke test
clear; clc;
root=fileparts(mfilename('fullpath'));
addpath(genpath(fullfile(root,'config')));
addpath(genpath(fullfile(root,'src')));
p=reference_cubesat();
cfg=simulation_config();

% A 90-degree active +Z rotation maps +X to +Y.
qz=[cos(pi/4);0;0;sin(pi/4)];
C=quat_to_dcm_b2i(qz);
assert(norm(C*[1;0;0]-[0;1;0])<1e-12);
assert(norm(C'*C-eye(3),'fro')<1e-12);

% Quaternion difference must vanish at identical orientations.
[phi,e]=attitude_error(qz,qz);
assert(norm(phi)<1e-12 && abs(e)<1e-12);

% Detumbling magnetic torque is perpendicular to B and dissipative.
w=[0.03;-0.02;0.01];q=[1;0;0;0];h=zeros(3,1);
B=[21e-6;-5e-6;15e-6];
a=adcs_commands('detumble',w,q,h,B,p,cfg);
assert(abs(dot(a.tauMag,B))<1e-16);
assert(dot(w,a.tauMag)<=1e-15);
assert(all(abs(a.m)<=p.mMax+eps));

% Reaction-wheel motor command at positive momentum limit must not
% continue charging the same wheel outward.
h=[p.hMax(1);0;0];
% Positive BODY-X attitude error creates an outward +X rotor command.
qOut=[cos(0.1);sin(0.1);0;0];
a=adcs_commands('point_no_dump',zeros(3,1),qOut,h,B,p,cfg);
assert(a.u(1)==0, ...
    'An outward wheel torque must be blocked at positive hMax.');
% The opposite attitude error must still permit an inward motor torque.
qIn=[cos(0.1);-sin(0.1);0;0];
a=adcs_commands('point_no_dump',zeros(3,1),qIn,h,B,p,cfg);
assert(a.u(1)<0, ...
    'An inward wheel torque must remain possible at positive hMax.');

% End-to-end test with real IGRF-14 (no external MATLAB workspace state).
cfg.finalTime_s=600;
cfg.modePolicy='scheduled';
cfg.detumbleEnd_s=300;
env=build_environment(cfg);
out=simulate_adcs(cfg,p,env);
assert(numel(out.t)==301);
assert(max(out.HbalanceRel)<5e-4);
assert(max(out.qNormError)<1e-9);
assert(all(isfinite(out.x(:))));
% Autonomous switching test: start nearly stationary and keep the
% threshold satisfied for 20 s. Both A/B cases must switch identically.
cfg.modePolicy='automatic';
cfg.detumbleDwell_s=20;
cfg.detumbleRateThreshold_deg_s=0.1;
cfg.minimumDetumble_s=0;
cfg.omega0_rad_s=zeros(3,1);
cfg.hwheel0_Nms=[1e-4;-8e-5;5e-5];
cfg.enableDumping=true;
a=simulate_adcs(cfg,p,env);
cfg.enableDumping=false;
b=simulate_adcs(cfg,p,env);
assert(~isempty(a.switchIndex) && ~isempty(b.switchIndex), ...
    'Automatic low-rate transition was not triggered.');
assert(a.switchIndex==b.switchIndex);
assert(max(abs(a.x(1:a.switchIndex,:)-b.x(1:b.switchIndex,:)),[],'all')<1e-12);
assert(max(a.HbalanceRel)<5e-4 && max(b.HbalanceRel)<5e-4);

% Test external torque pulse selection and physical frame mapping.
events=disturbance_events();
cfgEventCheck=simulation_config();
validate_disturbance_events(events,cfgEventCheck);
active=custom_torque_at_midpoint(events,5010);
inactive=custom_torque_at_midpoint(events,5022);
assert(norm(active.body-events(1).vector)<1e-14);
assert(norm(inactive.body)<1e-14);
% Multiple concurrent finite torques must add in their declared frame.
overlapEvents=events;
overlapEvents(2)=struct('type','torque','time_s',5000, ...
    'duration_s',20,'frame','BODY','vector',[0;2e-6;0]);
combo=custom_torque_at_midpoint(overlapEvents,5010);
assert(norm(combo.body-(events(1).vector+[0;2e-6;0]))<1e-14);

% Test exact inertial jump generated by an ideal angular impulse.
xj=[zeros(3,1);[1;0;0;0];zeros(3,1);zeros(3,1)];
[xpost,dHeci]=apply_impulses_at_time(xj,events,8000,p);
assert(norm(dHeci-events(2).vector)<1e-14);
assert(norm(p.J*xpost(1:3)-events(2).vector)<1e-14);
assert(norm(xpost(11:13)-events(2).vector)<1e-14);
assert(norm(xpost(4:7)-xj(4:7))<1e-14);

% End-to-end test for an impulse EXACTLY at t=0. This edge case
% must not double-count the jump in the inertial momentum balance.
cfg0=simulation_config();
cfg0.finalTime_s=240;
cfg0.detumbleEnd_s=120;
cfg0.modePolicy='scheduled';
impulse0=[1e-5;-2e-6;3e-6];
cfg0.events=struct('type','impulse','time_s',0, ...
    'duration_s',0,'frame','BODY','vector',impulse0);
env0=build_environment(cfg0);
out0=simulate_adcs(cfg0,p,env0);
C0=quat_to_dcm_b2i(cfg0.q0);
assert(norm(out0.Heci(1,:)'-out0.H0eci_pre_events- ...
    C0*impulse0)<1e-12, ...
    't=0 impulse must produce precisely the requested momentum jump.');
assert(norm(out0.x(1,11:13)'-C0*impulse0)<1e-12, ...
    't=0 impulse integral must contain the requested impulse.');
assert(max(out0.HbalanceRel)<5e-4, ...
    'Impulse at t=0 violates the inertial momentum balance.');

% End-to-end regression with both a finite pulse and a later impulse.
cfgE=cfg0;
cfgE.events(1)=struct('type','torque','time_s',60, ...
    'duration_s',20,'frame','BODY','vector',[3e-6;-1e-6;0]);
cfgE.events(2)=struct('type','impulse','time_s',140, ...
    'duration_s',0,'frame','ECI','vector',[2e-5;0;0]);
validate_disturbance_events(cfgE.events,cfgE);
outE=simulate_adcs(cfgE,p,env0);
cfgClean=cfgE;cfgClean.events=struct([]);
outClean=simulate_adcs(cfgClean,p,env0);
assert(norm(outE.omega(end,:)-outClean.omega(end,:))>1e-9, ...
    'Event-driven run should not coincide with no-event run on short test.');
assert(max(outE.HbalanceRel)<5e-4, ...
    'End-to-end custom-event momentum balance failed.');

% 3D angular-rate comparison must use the same inertial frame.
% The baseline and perturbed bodies below have DIFFERENT orientations,
% yet their angular velocity vectors in ECI are IDENTICAL.
testBase.t=[0;1];
testBase.q=repmat([1 0 0 0],2,1);
testBase.omega=repmat([1 0 0],2,1);
testBase.h=zeros(2,3);
testPert.t=testBase.t;
testPert.q=repmat(qz',2,1);
testPert.omega=repmat([0 -1 0],2,1);
testPert.h=zeros(2,3);
frameComparison=event_recovery_metrics( ...
    testBase,testPert,struct([]),0.1,1);
assert(max(frameComparison.angular_rate_difference_deg_s)<1e-10, ...
    'Angular-rate difference must be calculated in a common frame.');

fprintf('All integrated CubeSat tests PASSED.\n');
