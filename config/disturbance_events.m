function events = disturbance_events()
%DISTURBANCE_EVENTS Optional user-defined events for the virtual CubeSat.
% No event below is claimed to be a measured impact or flight disturbance.
%
% type='torque' : vector in N*m, applied for duration_s seconds.
% type='impulse': vector in N*m*s, applied instantaneously at time_s.
% frame='BODY' or 'ECI'. All event boundaries must align with cfg.dt_s.
% Overlapping finite torques are summed componentwise in their frames.
%
% Set events = struct([]) to switch all user disturbances OFF.

events(1) = struct( ...
    'type','torque', ...
    'time_s',5000, ...
    'duration_s',20, ...
    'frame','BODY', ...
    'vector',[3e-6;-1e-6;0]);

events(2) = struct( ...
    'type','impulse', ...
    'time_s',8000, ...
    'duration_s',0, ...
    'frame','ECI', ...
    'vector',[6e-5;0;0]);
end
