function validate_disturbance_events(events,cfg)
%VALIDATE_DISTURBANCE_EVENTS Reject ambiguous units, frames and off-grid events.
if isempty(events)
    return;
end
required={'type','time_s','duration_s','frame','vector'};
for k=1:numel(events)
    e=events(k);
    assert(all(isfield(e,required)), ...
        'An event must have type,time_s,duration_s,frame,vector.');
    assert(ischar(e.type) || isstring(e.type));
    assert(ischar(e.frame) || isstring(e.frame));
    assert(any(strcmpi(e.type,{'torque','impulse'})), ...
        'Event type must be torque or impulse.');
    assert(any(strcmpi(e.frame,{'BODY','ECI'})), ...
        'Event frame must be BODY or ECI.');
    assert(isnumeric(e.vector) && isequal(size(e.vector),[3 1]) && ...
        isreal(e.vector) && all(isfinite(e.vector)), ...
        'Event vector must be a finite real 3x1 vector.');
    assert(isnumeric(e.time_s) && isscalar(e.time_s) && ...
        isfinite(e.time_s) && e.time_s>=0 && e.time_s<cfg.finalTime_s, ...
        'Event time must lie in [0, finalTime_s).');
    assert(abs(e.time_s/cfg.dt_s-round(e.time_s/cfg.dt_s))<1e-9, ...
        'Event time must align with the attitude integration time grid.');
    if strcmpi(e.type,'torque')
        assert(isscalar(e.duration_s) && isfinite(e.duration_s) && ...
            e.duration_s>0 && ...
            e.time_s+e.duration_s<=cfg.finalTime_s, ...
            'Finite torque requires positive duration inside the simulation.');
        assert(abs(e.duration_s/cfg.dt_s- ...
            round(e.duration_s/cfg.dt_s))<1e-9, ...
            'Torque duration must align with the integration grid.');
    else
        assert(isscalar(e.duration_s) && e.duration_s==0, ...
            'Impulse must have zero duration.');
    end
end
end
